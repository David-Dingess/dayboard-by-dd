export function applyAddEvent(list: DayboardEvent[], event: DayboardEvent): DayboardEvent[] {
  if (list.some((e) => e.id === event.id)) {
    throw new Error(`There is already an event called that on ${event.start.slice(0, 10)}.`);
  }
  return [...list, event];
}

/**
 * Edit in place, keeping the id and bumping `seq`.
 *
 * THE ID NEVER MOVES, even when the title and the date both change. iOS matches
 * events by UID: a new id reaches the phone as a cancellation and a fresh
 * invitation rather than as an edit, and the old one may simply persist. `seq`
 * going up is the signal that says "same event, new details" — which is why it
 * is here and not left to the caller.
 */
export function applyEditEvent(
  list: DayboardEvent[],
  id: string,
  patch: Partial<DayboardEvent>,
  now: string,
): DayboardEvent[] {
  let found = false;
  const next = list.map((event) => {
    if (event.id !== id) return event;
    found = true;
    return { ...event, ...patch, id: event.id, seq: event.seq + 1, updatedAt: now };
  });
  if (!found) throw new Error(`No event with id "${id}".`);
  return next;
}

export function applyRemoveEvent(list: DayboardEvent[], id: string): DayboardEvent[] {
  if (!list.some((e) => e.id === id)) throw new Error(`No event with id "${id}".`);
  return list.filter((event) => event.id !== id);
}

/**
 * A form's answers as a stored event.
 *
 * `parseFlexible` decides all-day from the shape of the value, the same way the
 * CLI has always done it: a bare date is all-day, anything with a time is not.
 * An all-day END is made exclusive here — you pick the last day you mean, and
 * RFC 5545 stores the morning after.
 */
export function buildCuratedEvent(input: EventInput, now: string, id?: string): DayboardEvent {
  const start = parseFlexible(input.start);
  const end = input.end ? parseFlexible(input.end) : null;

  if (end && end.value < start.value) throw new Error("That ends before it starts.");

  return EventFileSchema.element.parse({
    id: id ?? curatedId(input.layer, input.title, start.value.slice(0, 10)),
    layer: input.layer,
    title: input.title.trim(),
    start: start.value,
    end: end?.value,
    allDay: start.allDay,
    tz: zone(),
    location: input.location?.trim() || undefined,
    url: input.url?.trim() || undefined,
    notes: input.notes?.trim() || undefined,
    source: { kind: "curated" },
    status: input.status,
    recurrence: input.recurrence,
    seq: 0,
    updatedAt: now,
  });
}

/** Which stored event an id refers to, instance or not. */
export function resolveMaster(id: string): string {
  return masterId(id);
}

