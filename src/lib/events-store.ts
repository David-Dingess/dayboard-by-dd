import { readFileSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { writeJsonAtomic } from "./atomic";
import { curatedId } from "./uid";
import { parseFlexible, zone } from "./time";
import { masterId } from "./recur";
import {
  EventFileSchema,
  EventInputSchema,
  type DayboardEvent,
  type EventInput,
} from "./schema";

/**
 * Reading and writing `data/layers/*.json` — the calendar's own storage.
 *
 * THIS IS THE ONE BOARD-WRITTEN THING UNDER data/layers/, and the rule it looks
 * like it breaks is worth stating. Everything else the board writes lives at
 * `data/` root, because loadCuratedEvents parses every JSON file under layers/
 * and cache/ as an array of events — so a to-do file there would be read,
 * rejected and logged on every render. These ARE arrays of events. They belong
 * here; nothing else does.
 *
 * The other half of that rule was the module cache in layers.ts, which held
 * these files for the life of the process and would have made every write
 * invisible until a restart. It now covers data/cache/ only. See its docblock.
 *
 * Pure functions plus fs, and NOTHING from `next/*` — scripts/event.ts loads
 * this under plain tsx, so the CLI, the chat skill and the editor all write
 * through one validation and one atomic save. The Next-only half is in
 * event-actions.ts.
 */

const DATA = path.join(process.cwd(), "data");
const LAYERS = path.join(DATA, "layers");

export function layerFile(layer: string): string {
  return path.join(LAYERS, `${layer}.json`);
}

/**
 * The layers the board may write to: the ones with a file of their own.
 *
 * Not every layer qualifies. The teams are snapshots of upstream
 * feeds under data/cache/, rewritten wholesale by the refresh routine — an event
 * added to one would vanish on the next run, so the editor never offers them.
 */
export function writableLayers(): string[] {
  if (!existsSync(LAYERS)) return ["personal"];
  const found = readdirSync(LAYERS)
    .filter((name) => name.endsWith(".json"))
    .map((name) => name.slice(0, -5))
    // Generated by the program, not by hand — data/layers/health.json does not
    // exist and must not be created. See health-events.ts.
    .filter((id) => id !== "health");
  return found.length ? found : ["personal"];
}

/** Read one layer's file. Uncached, for the reason in the docblock above. */
export function loadLayerFile(layer: string): DayboardEvent[] {
  try {
    return EventFileSchema.parse(JSON.parse(readFileSync(layerFile(layer), "utf8")));
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw new Error(`data/layers/${layer}.json is unreadable: ${(err as Error).message.split("\n")[0]}`);
  }
}

/**
 * Sort, validate, write atomically.
 *
 * `scripts/event.ts` has always sorted and validated here; the atomic part is
 * new and is what a second writer costs. A plain writeFileSync is fine while a
 * CLI is the only writer, and stops being fine the moment a render can read the
 * file halfway through a Server Action writing it.
 */
export function saveLayerFile(layer: string, events: DayboardEvent[]): void {
  const sorted = [...events].sort((a, b) => a.start.localeCompare(b.start) || a.id.localeCompare(b.id));
  writeJsonAtomic(layerFile(layer), JSON.stringify(EventFileSchema.parse(sorted), null, 2) + "\n");
}

